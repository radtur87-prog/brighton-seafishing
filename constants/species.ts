export const SPECIES_BY_ID = Object.fromEntries(SPECIES.map((s) => [s.id, s])) as Record<string, Species>;

export function normalize(text: string): string {
  return text
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[()]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/** Finds the encyclopedia entry for whatever the user typed as species ("Guppy samec", "neónky"). */
export function findSpecies(text: string): Species | null {
  const query = normalize(text);
  if (!query) return null;
  const exact = SPECIES.find((s) => normalize(s.name) === query || s.aliases.includes(query));
  if (exact) return exact;
  // Longest alias contained in the text wins ("corydoras aeneus" beats "corydoras").
  let best: { species: Species; length: number } | null = null;
  for (const s of SPECIES) {
    for (const alias of s.aliases) {
      const re = new RegExp(`(^|\\s)${alias.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}(\\s|$)`);
      if (re.test(query) && (!best || alias.length > best.length)) best = { species: s, length: alias.length };
    }
  }
  return best?.species ?? null;
}

/** Catalogue search by name, latin name or alias. */
export function searchSpecies(text: string): Species[] {
  const query = normalize(text);
  if (!query) return SPECIES;
  return SPECIES.filter(
    (s) => normalize(s.name).includes(query) || normalize(s.latin).includes(query) || s.aliases.some((a) => a.includes(query))
  );
}

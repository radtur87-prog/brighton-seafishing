// Freshwater species encyclopedia used for the catalogue, compatibility checks and bioload.
// Values are typical aquarium ranges (adult size, °C, pH, GH in °dH), not hard limits.

export type Temperament = 'peaceful' | 'semi' | 'aggressive';
export type Zone = 'top' | 'middle' | 'bottom' | 'all';
export type CareLevel = 'easy' | 'medium' | 'hard';

export interface Species {
  id: string;
  name: string;
  latin: string;
  /** Lower-case names people type, without diacritics ("guppy", "gupka"). */
  aliases: string[];
  emoji: string;
  temp: [number, number];
  ph: [number, number];
  gh: [number, number];
  /** Adult body length in cm. */
  sizeCm: number;
  /** Bioload in "cm of fish" when the body length misleads (thin loaches, shrimp, snails). */
  bioloadCm?: number;
  minLiters: number;
  temperament: Temperament;
  /** Smallest sensible group; 1 = can live alone. */
  minGroup: number;
  zone: Zone;
  care: CareLevel;
  diet: string;
  note: string;
  finNipper?: boolean;
  longFins?: boolean;
  /** Eats any fish or shrimp up to this length (cm). */
  preyMaxCm?: number;
  /** Two or more in one tank fight (male bettas). */
  oneMalePerTank?: boolean;
  /** Attacks long-finned, colourful fish. */
  attacksLongFins?: boolean;
  invertebrate?: boolean;
  /** Large but leaves shrimp alone. */
  shrimpSafe?: boolean;
}

